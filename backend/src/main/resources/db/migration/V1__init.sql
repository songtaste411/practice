-- 金额一律用「分」(bigint)。不要用 double / float 存钱。
-- 表名避开 order、user 这种保留字。

CREATE TABLE app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(64) NOT NULL UNIQUE,
    password_hash VARCHAR(120) NOT NULL,
    display_name VARCHAR(64) NOT NULL,
    role_code VARCHAR(32) NOT NULL
);

CREATE TABLE sku (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku_code VARCHAR(64) NOT NULL UNIQUE,
    name VARCHAR(128) NOT NULL,
    price_cent BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL
);

CREATE TABLE inventory_stock (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku_id BIGINT NOT NULL UNIQUE,
    available_qty INT NOT NULL,
    reserved_qty INT NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    updated_at TIMESTAMP NOT NULL
);

CREATE TABLE customer_order (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no VARCHAR(40) NOT NULL UNIQUE,
    status VARCHAR(32) NOT NULL,
    total_cent BIGINT NOT NULL,
    buyer_name VARCHAR(64) NOT NULL,
    idempotency_key VARCHAR(80),
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL
);

CREATE TABLE order_line (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    sku_id BIGINT NOT NULL,
    sku_code VARCHAR(64) NOT NULL,
    sku_name VARCHAR(128) NOT NULL,
    quantity INT NOT NULL,
    price_cent BIGINT NOT NULL
);

CREATE TABLE payment_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    pay_no VARCHAR(64) NOT NULL UNIQUE,
    amount_cent BIGINT NOT NULL,
    status VARCHAR(32) NOT NULL,
    created_at TIMESTAMP NOT NULL
);

-- 幂等表和业务写在同一个事务里。不要只放 Redis，Redis 丢了就会重复下单。
CREATE TABLE idempotency_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idem_key VARCHAR(80) NOT NULL UNIQUE,
    request_hash VARCHAR(64) NOT NULL,
    response_body VARCHAR(4000) NOT NULL,
    created_at TIMESTAMP NOT NULL
);

-- Outbox：业务提交和“待发送消息”同一事务。发送失败就保持 PENDING。
CREATE TABLE outbox_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type VARCHAR(64) NOT NULL,
    aggregate_id VARCHAR(64) NOT NULL,
    payload VARCHAR(2000) NOT NULL,
    status VARCHAR(32) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    published_at TIMESTAMP
);

CREATE INDEX idx_order_line_order ON order_line (order_id);
CREATE INDEX idx_outbox_status ON outbox_event (status, id);
